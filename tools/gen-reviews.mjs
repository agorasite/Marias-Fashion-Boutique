const ids = products.filter((p) => p.status !== 'archived');
const eligible = ids.slice(0, ids.length - 3); // last 3 products intentionally have no reviews
const base = new Date('2026-10-14T12:00:00.000Z').getTime();
const out = [];
for (let i = 0; i < 64; i += 1) {
  const p = i < eligible.length ? eligible[(i * 7) % eligible.length] : pick(eligible);
  const r = rnd();
  const rating = r < 0.55 ? 5 : r < 0.88 ? 4 : 3;
  const [title, body] = pick(POOL[catOf(p)][rating]);
  const createdAt = new Date(base - Math.floor(rnd() * 120 * 86400000)).toISOString();
  out.push({
    id: `rev-seed-${String(i + 1).padStart(3, '0')}`,
    productId: p.id,
    rating,
    title,
    body,
    author: `${pick(NAMES)} ${pick(INIT)}`,
    createdAt,
    seed: true,
  });
}
